BEGIN;

CREATE TABLE IF NOT EXISTS usuarios (
    id_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres VARCHAR(100) NOT NULL,
    apellidos VARCHAR(100) NOT NULL,
    email VARCHAR(180) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(30) NOT NULL DEFAULT 'ESTUDIANTE',
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP NULL,
    CONSTRAINT uq_usuarios_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS configuracionsistema (
    id_configuracion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave VARCHAR(120) NOT NULL,
    valor VARCHAR(1000) NOT NULL,
    descripcion VARCHAR(500) NULL,
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_configuracionsistema_clave UNIQUE (clave)
);

CREATE TABLE IF NOT EXISTS perfilesusuario (
    id_perfil INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    departamento VARCHAR(100) NULL,
    provincia VARCHAR(100) NULL,
    distrito VARCHAR(100) NULL,
    carrera_interes VARCHAR(150) NULL,
    nivel_estudio VARCHAR(100) NULL,
    institucion VARCHAR(180) NULL,
    fecha_actualizacion TIMESTAMP NULL,
    CONSTRAINT uq_perfilesusuario_id_usuario UNIQUE (id_usuario),
    CONSTRAINT fk_perfilesusuario_usuarios
        FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS alertas (
    id_alerta INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    nombre VARCHAR(100) NOT NULL,
    palabra_clave VARCHAR(150) NULL,
    region VARCHAR(100) NULL,
    activa BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_alertas_usuarios
        FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS auditoriaeventos (
    id_auditoria INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NULL,
    accion VARCHAR(100) NOT NULL,
    entidad VARCHAR(100) NOT NULL,
    detalle VARCHAR(1500) NULL,
    fecha_evento TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_auditoriaeventos_usuarios
        FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS authtokens (
    id_token BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    tipo VARCHAR(30) NOT NULL,
    token_hash CHAR(64) NOT NULL,
    expira_en TIMESTAMP NOT NULL,
    usado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_uso TIMESTAMP NULL,
    ip_solicitud VARCHAR(64) NULL,
    creado_en TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_authtokens_hash UNIQUE (token_hash),
    CONSTRAINT fk_authtokens_usuarios
        FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS documentosusuario (
    id_documento_usuario INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    tipo_documento VARCHAR(100) NOT NULL,
    nombre_archivo VARCHAR(255) NOT NULL,
    descripcion VARCHAR(500) NULL,
    fecha_emision DATE NULL,
    fecha_vencimiento DATE NULL,
    estado_validacion VARCHAR(40) NOT NULL DEFAULT 'PENDIENTE',
    observacion_validacion VARCHAR(500) NULL,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_documentosusuario_usuarios
        FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS favoritos (
    id_favorito INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    tipo VARCHAR(50) NOT NULL DEFAULT 'OPORTUNIDAD',
    referencia VARCHAR(250) NULL,
    datos_json TEXT NOT NULL,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    tipo_recurso VARCHAR(50) NULL,
    recurso_id VARCHAR(200) NULL,
    titulo VARCHAR(250) NULL,
    subtitulo VARCHAR(250) NULL,
    CONSTRAINT fk_favoritos_usuarios
        FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS historialconsultas (
    id_historial INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    tipo_consulta VARCHAR(80) NOT NULL,
    termino VARCHAR(250) NULL,
    filtros_json VARCHAR(4000) NULL,
    fecha_consulta TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_historialconsultas_usuarios
        FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS notificaciones (
    id_notificacion INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    titulo VARCHAR(180) NOT NULL,
    mensaje VARCHAR(1000) NOT NULL,
    tipo VARCHAR(50) NOT NULL DEFAULT 'GENERAL',
    leida BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_lectura TIMESTAMP NULL,
    CONSTRAINT fk_notificaciones_usuarios
        FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS seguimientospostulacion (
    id_seguimiento INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario INTEGER NOT NULL,
    id_postulacion VARCHAR(120) NOT NULL,
    titulo VARCHAR(220) NOT NULL,
    estado VARCHAR(50) NOT NULL DEFAULT 'EN_SEGUIMIENTO',
    notas VARCHAR(1000) NULL,
    fecha_creacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_seguimientospostulacion_usuario_postulacion
        UNIQUE (id_usuario, id_postulacion),
    CONSTRAINT fk_seguimientospostulacion_usuarios
        FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
);

CREATE TABLE IF NOT EXISTS usuarioemailestado (
    id_usuario INTEGER PRIMARY KEY,
    email_verificado BOOLEAN NOT NULL DEFAULT FALSE,
    fecha_verificacion TIMESTAMP NULL,
    fecha_actualizacion TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_usuarioemailestado_usuarios
        FOREIGN KEY (id_usuario) REFERENCES usuarios(id_usuario)
);

-- Índices de apoyo para claves foráneas / consultas frecuentes.
CREATE INDEX IF NOT EXISTS ix_alertas_id_usuario
    ON alertas(id_usuario);

CREATE INDEX IF NOT EXISTS ix_auditoriaeventos_id_usuario
    ON auditoriaeventos(id_usuario);

CREATE INDEX IF NOT EXISTS ix_authtokens_id_usuario
    ON authtokens(id_usuario);

CREATE INDEX IF NOT EXISTS ix_documentosusuario_id_usuario
    ON documentosusuario(id_usuario);

CREATE INDEX IF NOT EXISTS ix_favoritos_id_usuario
    ON favoritos(id_usuario);

CREATE INDEX IF NOT EXISTS ix_historialconsultas_id_usuario
    ON historialconsultas(id_usuario);

CREATE INDEX IF NOT EXISTS ix_notificaciones_id_usuario
    ON notificaciones(id_usuario);

CREATE INDEX IF NOT EXISTS ix_seguimientospostulacion_id_usuario
    ON seguimientospostulacion(id_usuario);

COMMIT;
